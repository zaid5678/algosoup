"""SignalSort: Streamlit UI. Run with `streamlit run app.py`."""

import os
import re

import streamlit as st
from dotenv import load_dotenv

from analyzer import MAX_CHARS, AnalysisError, analyse, get_api_key, get_model
from models import Analysis
from report import to_csv, to_markdown
from samples import DEMO_ANALYSIS, SAMPLE_FEEDBACK

MAX_RUNS_PER_SESSION = 10  # soft cost guard for a public demo; resets on page refresh

SENTIMENT_COLOURS = {"positive": "green", "negative": "red", "mixed": "orange", "neutral": "gray"}
PRIORITY_COLOURS = {"P1": "red", "P2": "orange", "P3": "blue"}
PRIORITY_LABELS = {"P1": "Do now", "P2": "Next", "P3": "Later"}

st.set_page_config(page_title="SignalSort · Customer feedback intelligence", page_icon="📡")

load_dotenv()
if not os.environ.get("GEMINI_API_KEY"):
    try:  # Streamlit Community Cloud exposes secrets via st.secrets
        os.environ["GEMINI_API_KEY"] = st.secrets["GEMINI_API_KEY"]
    except Exception:
        pass


def md(text: str) -> str:
    """Escape user/model text so Streamlit doesn't render it as Markdown or LaTeX ($)."""
    return re.sub(r"([\\`*_\[\]$~<>#|])", r"\\\1", text)


def badge(label: str, colour: str) -> str:
    return f":{colour}-background[{label}]"


def load_sample() -> None:
    st.session_state.feedback = SAMPLE_FEEDBACK


def clear_input() -> None:
    st.session_state.feedback = ""
    st.session_state.pop("result", None)


st.session_state.setdefault("runs", 0)

# ── Header ────────────────────────────────────────────────────────────────────
st.title("📡 SignalSort")
st.markdown(
    "#### Turn messy customer feedback into prioritised product decisions.\n"
    "Paste reviews, support tickets or interview notes. SignalSort's AI finds the recurring "
    "themes, gauges sentiment for each, backs them with **verbatim quotes checked against "
    "your text**, and recommends what to fix first."
)

# ── Input ─────────────────────────────────────────────────────────────────────
api_key_configured = bool(get_api_key())

st.text_area(
    "Customer feedback",
    key="feedback",
    height=260,
    placeholder="Paste feedback here, one item per line or paragraph…",
)
chars = len(st.session_state.get("feedback", "").strip())
caption = f"{chars:,} / {MAX_CHARS:,} characters"
if st.session_state.get("feedback") == SAMPLE_FEEDBACK:
    caption += " · **Sample dataset loaded** (fictional app “Trackly”)"
st.caption(caption)

col_sample, col_clear, col_go = st.columns([1.3, 0.8, 1.3])
col_sample.button("Load sample dataset", on_click=load_sample, width="stretch")
col_clear.button("Clear", on_click=clear_input, width="stretch")
analyse_clicked = col_go.button(
    "Analyse feedback", type="primary", width="stretch",
    disabled=st.session_state.runs >= MAX_RUNS_PER_SESSION,
)

if not api_key_configured:
    st.info(
        "AI analysis isn't configured on this server (no `GEMINI_API_KEY`). "
        "You can still preview a hand-written example report for the sample dataset."
    )
    if st.button("View example report"):
        st.session_state.result = {"analysis": DEMO_ANALYSIS, "source": "example"}
if st.session_state.runs >= MAX_RUNS_PER_SESSION:
    st.warning(f"This demo allows {MAX_RUNS_PER_SESSION} analyses per session.")

if analyse_clicked:
    st.session_state.pop("result", None)  # never show an old report next to a new error
    try:
        with st.spinner("Analysing feedback… this usually takes 15–40 seconds."):
            result = analyse(st.session_state.feedback)
        st.session_state.runs += 1
        st.session_state.result = {
            "analysis": result.analysis,
            "source": "ai",
            "model": result.model,
            "removed": result.removed_quotes,
            "chars": chars,
        }
    except AnalysisError as e:
        st.error(str(e))

# ── Results ───────────────────────────────────────────────────────────────────
result = st.session_state.get("result")
if result:
    analysis: Analysis = result["analysis"]
    st.divider()

    if result["source"] == "example":
        provenance = "Example report: hand-written for the sample dataset, not generated by AI."
        st.warning(f"**{provenance}** Add an API key to run a real analysis.", icon="🧪")
    else:
        provenance = f"AI-generated analysis ({result['model']}) of {result['chars']:,} characters of feedback."
        st.success(f"**AI analysis complete.** {provenance} Review before acting on it.", icon="✅")
        if result["removed"]:
            st.caption(
                f"🛡️ {result['removed']} suggested quote(s) were removed because they couldn't "
                "be matched word-for-word in your input."
            )

    st.subheader("Summary")
    with st.container(border=True):
        st.markdown(md(analysis.summary))
        m1, m2, m3 = st.columns(3)
        m1.metric("Overall sentiment", analysis.overall_sentiment.title())
        m2.metric("Themes", len(analysis.themes))
        m3.metric("Recommendations", len(analysis.recommendations))

    st.subheader("Themes")
    st.caption("Ordered by estimated prevalence. Prevalence is an AI estimate, not an exact count.")
    for theme in analysis.themes:
        with st.container(border=True):
            st.markdown(f"**{md(theme.name)}**")
            st.markdown(
                badge(theme.sentiment.title(), SENTIMENT_COLOURS[theme.sentiment]) + " "
                + badge(f"Est. prevalence: {theme.prevalence.title()}", "gray")
            )
            st.markdown(md(theme.description))
            if theme.quotes:
                for q in theme.quotes:
                    st.markdown(f"> “{md(q)}”")
            else:
                st.caption("No evidence quote could be verified in the input for this theme.")

    st.subheader("Recommendations")
    for rec in sorted(analysis.recommendations, key=lambda r: r.priority):
        with st.container(border=True):
            st.markdown(
                badge(f"{rec.priority} · {PRIORITY_LABELS[rec.priority]}", PRIORITY_COLOURS[rec.priority])
                + f" **{md(rec.action)}**"
            )
            st.markdown(md(rec.rationale))
            if rec.related_themes:
                st.caption("Themes: " + md(", ".join(rec.related_themes)))

    st.subheader("Export")
    d1, d2 = st.columns(2)
    d1.download_button("Download Markdown report", to_markdown(analysis, provenance),
                       file_name="signalsort-report.md", mime="text/markdown",
                       width="stretch")
    d2.download_button("Download CSV", to_csv(analysis), file_name="signalsort-report.csv",
                       mime="text/csv", width="stretch")

st.divider()
st.caption(
    "SignalSort sends the text you paste to Google's Gemini API and doesn't store it. "
    "This demo uses Gemini's free tier, where Google may use submitted content to improve "
    "its products, so don't paste personal or confidential data. "
    f"Model: {get_model()}."
)
