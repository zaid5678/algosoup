"""UI smoke tests using Streamlit's headless AppTest (no browser, no API calls)."""

from pathlib import Path

import pytest
from streamlit.testing.v1 import AppTest

import analyzer
from samples import SAMPLE_FEEDBACK

APP = str(Path(__file__).resolve().parent.parent / "app.py")


@pytest.fixture
def app(monkeypatch):
    monkeypatch.delenv("GEMINI_API_KEY", raising=False)
    monkeypatch.setattr("dotenv.load_dotenv", lambda *a, **k: False)  # ignore a local .env
    at = AppTest.from_file(APP, default_timeout=30)
    at.run()
    assert not at.exception
    return at


def button(at, label):
    return next(b for b in at.button if b.label == label)


def test_landing_page_without_key(app):
    assert app.title[0].value == "📡 SignalSort"
    assert any("isn't configured" in i.value for i in app.info)


def test_empty_submit_shows_error(app):
    button(app, "Analyse feedback").click().run()
    assert any("Paste some customer feedback" in e.value for e in app.error)


def test_sample_then_analyse_without_key_shows_config_error(app):
    button(app, "Load sample dataset").click().run()
    assert app.text_area[0].value == SAMPLE_FEEDBACK
    assert any("Sample dataset loaded" in c.value for c in app.caption)
    button(app, "Analyse feedback").click().run()
    assert any("No API key configured" in e.value for e in app.error)


def test_example_report_is_clearly_labelled(app):
    button(app, "View example report").click().run()
    assert not app.exception
    assert any("not generated by AI" in w.value for w in app.warning)
    headers = [s.value for s in app.subheader]
    assert headers == ["Summary", "Themes", "Recommendations", "Export"]


def test_ai_result_renders_with_provenance(app, monkeypatch):
    from tests.test_analyzer import FEEDBACK, VALID, FakeClient, ok

    real = analyzer.analyse
    monkeypatch.setattr("analyzer.analyse",
                        lambda text: real(text, client=FakeClient(ok(VALID)), model="fake-model"))
    at = AppTest.from_file(APP, default_timeout=30)
    at.run()
    at.text_area[0].set_value(FEEDBACK).run()
    button(at, "Analyse feedback").click().run()
    assert not at.exception
    assert any("AI analysis complete" in s.value for s in at.success)
    assert any("1 suggested quote(s) were removed" in c.value for c in at.caption)


def test_failed_analysis_clears_previous_report(app):
    button(app, "View example report").click().run()
    assert "Summary" in [s.value for s in app.subheader]
    app.text_area[0].set_value("x" * 31_000).run()
    button(app, "Analyse feedback").click().run()
    assert any("limit" in e.value for e in app.error)
    assert [s.value for s in app.subheader] == []
